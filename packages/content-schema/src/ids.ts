// data/ids.lock.yaml: stable numeric IDs for items (network and world.bin).
// Append-only: a number is never changed or reused, even after an item is removed.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parse } from "yaml";
import type { Diagnostic, SourceFile } from "./source.ts";

const HEADER = `# Stable numeric item IDs. Generated by \`make gen-ids\`; commit it with your change.
# Append-only: never edit, change or reuse a number, even if the item is deleted.
`;

export type IdsLock = Record<string, number>;

function lockItems(data: unknown): IdsLock {
  if (typeof data !== "object" || data === null) return {};
  const items = (data as Record<string, unknown>)["items"];
  if (typeof items !== "object" || items === null) return {};
  const out: IdsLock = {};
  for (const [k, v] of Object.entries(items)) if (typeof v === "number") out[k] = v;
  return out;
}

export function checkIdsLock(lock: SourceFile, itemIds: string[], base?: SourceFile): Diagnostic[] {
  const diags: Diagnostic[] = [];
  const at = (
    path: (string | number)[],
    message: string,
    severity: Diagnostic["severity"] = "error",
  ): void => {
    const pos = lock.locate(path);
    diags.push({
      severity,
      file: lock.file,
      path,
      message,
      ...(pos ? { line: pos.line, col: pos.col } : {}),
    });
  };
  const items = lockItems(lock.data);
  const byNumber = new Map<number, string>();
  for (const [id, num] of Object.entries(items)) {
    const other = byNumber.get(num);
    if (other !== undefined) at(["items", id], `number ${num} is already assigned to "${other}"`);
    else byNumber.set(num, id);
  }
  const defined = new Set(itemIds);
  for (const id of itemIds) {
    if (!(id in items)) at(["items"], `item "${id}" has no numeric id; run \`make gen-ids\``);
  }
  for (const id of Object.keys(items)) {
    if (!defined.has(id))
      at(
        ["items", id],
        `"${id}" is not defined in data/items (retired id; keep it, never reuse the number)`,
        "warning",
      );
  }
  if (base) {
    for (const [id, num] of Object.entries(lockItems(base.data))) {
      if (!(id in items))
        at(["items"], `"${id}" (${num}) was removed; ids.lock.yaml is append-only`);
      else if (items[id] !== num)
        at(
          ["items", id],
          `number changed from ${num} to ${items[id]}; ids.lock.yaml is append-only`,
        );
    }
  }
  return diags;
}

/** Item IDs in data/items/*.yaml, in file order. Invalid files are skipped (validate reports them). */
function readItemIds(dataDir: string): string[] {
  const dir = join(dataDir, "items");
  if (!existsSync(dir)) return [];
  const ids: string[] = [];
  for (const file of readdirSync(dir)
    .filter((f) => f.endsWith(".yaml"))
    .sort()) {
    const list: unknown = parse(readFileSync(join(dir, file), "utf8"));
    if (!Array.isArray(list)) continue;
    for (const item of list) {
      const id = (item as Record<string, unknown> | null)?.["id"];
      if (typeof id === "string") ids.push(id);
    }
  }
  return ids;
}

export function renderIdsLock(items: IdsLock): string {
  const lines = Object.entries(items)
    .sort((a, b) => a[1] - b[1])
    .map(([id, num]) => `  ${id}: ${num}`);
  return `${HEADER}items:${lines.length === 0 ? " {}" : `\n${lines.join("\n")}`}\n`;
}

/** Assigns the next free numbers to new items and rewrites the lock canonically. */
export function generateIdsLock(root: string): { added: string[]; text: string } {
  const dataDir = join(root, "data");
  const lockPath = join(dataDir, "ids.lock.yaml");
  const items = existsSync(lockPath) ? lockItems(parse(readFileSync(lockPath, "utf8"))) : {};
  let next = Math.max(0, ...Object.values(items)) + 1;
  const added: string[] = [];
  for (const id of readItemIds(dataDir)) {
    if (id in items) continue;
    if (next > 65535) throw new Error("ids.lock.yaml: ran out of 16-bit item ids");
    items[id] = next++;
    added.push(id);
  }
  const text = renderIdsLock(items);
  writeFileSync(lockPath, text);
  return { added, text };
}
