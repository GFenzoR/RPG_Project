// data/ids.lock.yaml: stable numeric IDs for items (network and world.bin), and the ids of
// the reward chests (docs/02 "Libros y cofres"), each with its item: a chest id is the
// storage key chest.<id> of every character that opened it.
// Append-only: a number or a chest id is never changed or reused, even after its item is removed.
// An item deleted on purpose is listed under `retired` (make gen-ids RETIRE=1): its number
// stays taken, without the warning a deleted item gives.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parse } from "yaml";
import type { Diagnostic, SourceFile } from "./source.ts";

const HEADER = `# Stable numeric item IDs. Generated by \`make gen-ids\`; commit it with your change.
# Append-only: never edit, change or reuse a number, even if the item is deleted.
`;

export type IdsLock = Record<string, number>;
/** Chest id → the item whose chest block has it. */
export type ChestsLock = Record<string, string>;

/** The comment over the chests of the lock: what a chest id is and why it never changes. */
const CHESTS_HEADER = `
# Reward chests (docs/02 "Libros y cofres"): chest id -> its item. A chest id is the storage
# key chest.<id> of every character that opened it: never rename or reuse one.
`;

function lockItems(data: unknown): IdsLock {
  if (typeof data !== "object" || data === null) return {};
  const items = (data as Record<string, unknown>)["items"];
  if (typeof items !== "object" || items === null) return {};
  const out: IdsLock = {};
  for (const [k, v] of Object.entries(items)) if (typeof v === "number") out[k] = v;
  return out;
}

/** The comment over the retired items of the lock. */
const RETIRED_HEADER = `
# Retired items: deleted from data/items on purpose (make gen-ids RETIRE=1); their numbers
# under items stay taken forever.
`;

function lockRetired(data: unknown): string[] {
  if (typeof data !== "object" || data === null) return [];
  const list = (data as Record<string, unknown>)["retired"];
  return Array.isArray(list) ? list.filter((v): v is string => typeof v === "string") : [];
}

function lockChests(data: unknown): ChestsLock {
  if (typeof data !== "object" || data === null) return {};
  const chests = (data as Record<string, unknown>)["chests"];
  if (typeof chests !== "object" || chests === null) return {};
  const out: ChestsLock = {};
  for (const [k, v] of Object.entries(chests)) if (typeof v === "string") out[k] = v;
  return out;
}

/**
 * Checks the lock against the item ids of data/items and their chests (chest id → item,
 * docs/02 "Libros y cofres"), and against the lock of the base revision when there is one:
 * every item has a number and every chest its entry, a number is never shared, and nothing
 * of the base changed. A chest id locked to another item is a reused one, and an item whose
 * locked chest id is not the one it has now renamed it: whoever opened the chest under its
 * old id would open it again.
 */
export function checkIdsLock(
  lock: SourceFile,
  itemIds: string[],
  base?: SourceFile,
  chests: ReadonlyMap<string, string> = new Map(),
): Diagnostic[] {
  const diags: Diagnostic[] = [];
  const at = (
    path: (string | number)[],
    message: string,
    severity: Diagnostic["severity"] = "error",
  ): void => {
    const pos = lock.locate(path);
    diags.push({
      severity,
      file: lock.file,
      path,
      message,
      ...(pos ? { line: pos.line, col: pos.col } : {}),
    });
  };
  const items = lockItems(lock.data);
  const byNumber = new Map<number, string>();
  for (const [id, num] of Object.entries(items)) {
    const other = byNumber.get(num);
    if (other !== undefined) at(["items", id], `number ${num} is already assigned to "${other}"`);
    else byNumber.set(num, id);
  }
  const defined = new Set(itemIds);
  for (const id of itemIds) {
    if (!(id in items)) at(["items"], `item "${id}" has no numeric id; run \`make gen-ids\``);
  }
  const retired = lockRetired(lock.data);
  for (const id of Object.keys(items)) {
    if (!defined.has(id) && !retired.includes(id))
      at(
        ["items", id],
        `"${id}" is not defined in data/items (retired id? keep it, never reuse the number; make gen-ids RETIRE=1 lists it under retired)`,
        "warning",
      );
  }
  for (const [i, id] of retired.entries()) {
    if (!(id in items)) at(["retired", i], `retired "${id}" has no number under items`);
    else if (defined.has(id))
      at(
        ["retired", i],
        `"${id}" is in data/items again: run \`make gen-ids\` (it leaves retired)`,
      );
  }
  const locked = lockChests(lock.data);
  const chestOf = new Map<string, string>(); // item → its chest id in data/items
  for (const [cid, item] of chests) chestOf.set(item, cid);
  for (const [cid, item] of chests) {
    const owner = locked[cid];
    if (owner === undefined)
      at(["chests"], `chest "${cid}" (item "${item}") is not locked; run \`make gen-ids\``);
    else if (owner !== item)
      at(
        ["chests", cid],
        `chest id "${cid}" belongs to item "${owner}", not "${item}": a chest id is the storage key chest.<id> of whoever opened it, never reuse one`,
      );
  }
  for (const [cid, item] of Object.entries(locked)) {
    if (chests.has(cid)) continue;
    const now = chestOf.get(item);
    if (now !== undefined)
      at(
        ["chests", cid],
        `item "${item}" has chest id "${now}" now: never rename a chest id (it is the storage key chest.<id>; whoever opened it would open it again)`,
      );
    else
      at(
        ["chests", cid],
        `chest "${cid}" is not in data/items (retired chest; keep it, never reuse the id)`,
        "warning",
      );
  }
  if (base) {
    for (const [id, num] of Object.entries(lockItems(base.data))) {
      if (!(id in items))
        at(["items"], `"${id}" (${num}) was removed; ids.lock.yaml is append-only`);
      else if (items[id] !== num)
        at(
          ["items", id],
          `number changed from ${num} to ${items[id]}; ids.lock.yaml is append-only`,
        );
    }
    for (const [cid, item] of Object.entries(lockChests(base.data))) {
      if (!(cid in locked))
        at(["chests"], `chest "${cid}" ("${item}") was removed; ids.lock.yaml is append-only`);
      else if (locked[cid] !== item)
        at(
          ["chests", cid],
          `item changed from "${item}" to "${locked[cid]}"; ids.lock.yaml is append-only`,
        );
    }
  }
  return diags;
}

/**
 * Item IDs in data/items/*.yaml, in file order, and their chests ([chest id, item], in the
 * same order). Invalid files are skipped (validate reports them).
 */
function readItems(dataDir: string): { ids: string[]; chests: [string, string][] } {
  const dir = join(dataDir, "items");
  const ids: string[] = [];
  const chests: [string, string][] = [];
  if (!existsSync(dir)) return { ids, chests };
  for (const file of readdirSync(dir)
    .filter((f) => f.endsWith(".yaml"))
    .sort()) {
    const list: unknown = parse(readFileSync(join(dir, file), "utf8"));
    if (!Array.isArray(list)) continue;
    for (const item of list) {
      const it = item as Record<string, unknown> | null;
      const id = it?.["id"];
      if (typeof id !== "string") continue;
      ids.push(id);
      const chest = it?.["chest"];
      const cid =
        typeof chest === "object" && chest !== null
          ? (chest as Record<string, unknown>)["id"]
          : undefined;
      if (typeof cid === "string") chests.push([cid, id]);
    }
  }
  return { ids, chests };
}

/**
 * The lock's text: the retired items (if any) by number, the chests (if any) in the order
 * they came, then the items by number, last, so that new items and chests keep going at
 * the end of their lists.
 */
export function renderIdsLock(
  items: IdsLock,
  chests: ChestsLock = {},
  retired: readonly string[] = [],
): string {
  const lines = Object.entries(items)
    .sort((a, b) => a[1] - b[1])
    .map(([id, num]) => `  ${id}: ${num}`);
  const chestLines = Object.entries(chests).map(([cid, item]) => `  ${cid}: ${item}`);
  const gone = [...retired]
    .sort((a, b) => (items[a] ?? 0) - (items[b] ?? 0))
    .map((id) => `  - ${id}`);
  return (
    HEADER +
    (gone.length === 0 ? "" : `${RETIRED_HEADER}retired:\n${gone.join("\n")}\n`) +
    (chestLines.length === 0 ? "" : `${CHESTS_HEADER}chests:\n${chestLines.join("\n")}\n`) +
    `items:${lines.length === 0 ? " {}" : `\n${lines.join("\n")}`}\n`
  );
}

/**
 * Assigns the next free numbers to new items, appends the new chests and rewrites the lock
 * canonically. A chest whose id is locked to another item, or whose item is locked under
 * another chest id, is not added: that is a reuse or a rename, which validate reports. With
 * `retire`, every locked item no longer in data/items goes under `retired` (deleted on
 * purpose); an item back in data/items always leaves it.
 */
export function generateIdsLock(
  root: string,
  opts: { retire?: boolean } = {},
): {
  added: string[];
  chests: string[];
  retired: string[];
  text: string;
} {
  const dataDir = join(root, "data");
  const lockPath = join(dataDir, "ids.lock.yaml");
  const lock: unknown = existsSync(lockPath) ? parse(readFileSync(lockPath, "utf8")) : undefined;
  const items = lockItems(lock);
  const chests = lockChests(lock);
  const data = readItems(dataDir);
  let next = Math.max(0, ...Object.values(items)) + 1;
  const added: string[] = [];
  for (const id of data.ids) {
    if (id in items) continue;
    if (next > 65535) throw new Error("ids.lock.yaml: ran out of 16-bit item ids");
    items[id] = next++;
    added.push(id);
  }
  const lockedItems = new Set(Object.values(chests));
  const addedChests: string[] = [];
  for (const [cid, item] of data.chests) {
    if (cid in chests || lockedItems.has(item)) continue;
    chests[cid] = item;
    lockedItems.add(item);
    addedChests.push(cid);
  }
  const defined = new Set(data.ids);
  const retired = lockRetired(lock).filter((id) => id in items && !defined.has(id));
  const newlyRetired: string[] = [];
  if (opts.retire)
    for (const id of Object.keys(items))
      if (!defined.has(id) && !retired.includes(id)) {
        retired.push(id);
        newlyRetired.push(id);
      }
  const text = renderIdsLock(items, chests, retired);
  writeFileSync(lockPath, text);
  return { added, chests: addedChests, retired: newlyRetired, text };
}
