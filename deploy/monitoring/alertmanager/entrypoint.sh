#!/bin/sh
# Alertmanager entrypoint (T4.4): writes its config from environment variables, so no
# credential lives in the repo, then runs Alertmanager. Runs in the prom/alertmanager image
# (busybox sh). Secrets go to files under $SECRETS (tmpfs), never into the YAML.
#
# Channels (all optional; any combination; none = alerts only visible in Grafana and
# Alertmanager's own UI):
#   ALERT_DISCORD_WEBHOOK_URL                      Discord channel webhook
#   ALERT_TELEGRAM_BOT_TOKEN + ALERT_TELEGRAM_CHAT_ID  Telegram bot
#   ALERT_WEBHOOK_URL                              any HTTP endpoint (JSON POST)
#   ALERT_EMAIL_TO + ALERT_SMTP_SMARTHOST (host:port) + ALERT_SMTP_FROM
#     [+ ALERT_SMTP_USER + ALERT_SMTP_PASSWORD]    e-mail
#
#   entrypoint.sh --print   only print the generated config (CI validates it with amtool)
set -eu

OUT="${ALERTMANAGER_CONFIG:-/tmp/alertmanager.yml}"
SECRETS="${ALERTMANAGER_SECRETS:-/tmp/secrets}"
mkdir -p "$SECRETS" "$(dirname "$OUT")"
chmod 700 "$SECRETS"

secret() { # secret NAME VALUE: writes VALUE to $SECRETS/NAME and prints the path
	umask 077
	printf '%s' "$2" >"$SECRETS/$1"
	printf '%s' "$SECRETS/$1"
}

# YAML double-quoted scalar of a non-secret value (chat id, addresses).
quote() { printf '"%s"' "$(printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g')"; }

channels=""
receiver=""
if [ -n "${ALERT_DISCORD_WEBHOOK_URL:-}" ]; then
	channels="$channels discord"
	receiver="$receiver
    discord_configs:
      - webhook_url_file: $(secret discord "$ALERT_DISCORD_WEBHOOK_URL")
        send_resolved: true"
fi
if [ -n "${ALERT_TELEGRAM_BOT_TOKEN:-}" ] && [ -n "${ALERT_TELEGRAM_CHAT_ID:-}" ]; then
	channels="$channels telegram"
	receiver="$receiver
    telegram_configs:
      - bot_token_file: $(secret telegram "$ALERT_TELEGRAM_BOT_TOKEN")
        chat_id: ${ALERT_TELEGRAM_CHAT_ID}
        parse_mode: HTML
        send_resolved: true"
fi
if [ -n "${ALERT_WEBHOOK_URL:-}" ]; then
	channels="$channels webhook"
	receiver="$receiver
    webhook_configs:
      - url_file: $(secret webhook "$ALERT_WEBHOOK_URL")
        send_resolved: true"
fi
if [ -n "${ALERT_EMAIL_TO:-}" ] && [ -n "${ALERT_SMTP_SMARTHOST:-}" ] && [ -n "${ALERT_SMTP_FROM:-}" ]; then
	channels="$channels email"
	auth=""
	if [ -n "${ALERT_SMTP_USER:-}" ]; then
		auth="
        auth_username: $(quote "$ALERT_SMTP_USER")
        auth_password_file: $(secret smtp "${ALERT_SMTP_PASSWORD:-}")"
	fi
	receiver="$receiver
    email_configs:
      - to: $(quote "$ALERT_EMAIL_TO")
        from: $(quote "$ALERT_SMTP_FROM")
        smarthost: $(quote "$ALERT_SMTP_SMARTHOST")$auth
        send_resolved: true"
fi

cat >"$OUT" <<YAML
# Generated by deploy/monitoring/alertmanager/entrypoint.sh at container start.
route:
  receiver: default
  group_by: [alertname, severity]
  group_wait: 30s
  group_interval: 5m
  repeat_interval: 4h
  routes:
    # Critical alerts repeat sooner.
    - matchers: [severity="critical"]
      receiver: default
      repeat_interval: 1h
receivers:
  - name: default$receiver
inhibit_rules:
  # While the server is down, its other alerts are noise.
  - source_matchers: [alertname="GameServerDown"]
    target_matchers: [severity="warning"]
YAML

if [ "${1:-}" = "--print" ]; then
	cat "$OUT"
	exit 0
fi
echo "alertmanager: notification channels:${channels:- none (alerts only in Grafana and the Alertmanager UI)}"
exec /bin/alertmanager --config.file="$OUT" --storage.path=/alertmanager \
	--web.listen-address=:9093 --cluster.listen-address= "$@"
